document.addEventListener("DOMContentLoaded", function () {

    const select = document.getElementById("landingLang");

    console.log("Landing JS loaded");
    console.log("Language selector:", select);

    if (!select) {
        return;
    }

    // Apply saved language when page loads
    const savedLanguage =
        localStorage.getItem("ipSaktiLanguage") || "en";

    applyLandingLanguage(savedLanguage);

    // Change language immediately when dropdown changes
    select.addEventListener("change", function () {

        console.log(
            "Selected language:",
            this.value
        );

        applyLandingLanguage(this.value);
    });

});